"""
backend/app/models/user.py
--------------------------
User account model.

A User is anyone who can interact with SeatLock: regular attendees and
administrators. The role field controls what a user is allowed to do.
Passwords are NEVER stored in plain text — only bcrypt hashes go here.
"""

import uuid
import enum

from sqlalchemy import Enum as PgEnum, String, UniqueConstraint, text
from sqlalchemy.dialects.postgresql import UUID
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.core.database import Base


class UserRole(str, enum.Enum):
    """
    The roles a user can hold in SeatLock.

    STUDENT   : Standard attendee / student who reserves seats.
    ORGANIZER : Event creator / manager who coordinates events.
    ADMIN     : System administrator with full elevated permissions.
    ATTENDEE  : Legacy alias for backward compatibility.
    """
    STUDENT = "student"
    ORGANIZER = "organizer"
    ADMIN = "admin"
    ATTENDEE = "attendee"


class User(Base):
    """
    Maps to the 'users' table.

    Columns
    -------
    id            : UUID primary key — generated by the database on INSERT.
    username      : Unique login name; max 50 chars; cannot be blank.
    password_hash : bcrypt hash of the user's password. Never the plaintext.
    role          : UserRole enum — stored as a PostgreSQL ENUM type so the DB
                    enforces valid values independently of the application.

    Relationships
    -------------
    holds    : one User → many Holds   (a user can hold multiple seat groups)
    bookings : one User → many Bookings
    """

    __tablename__ = "users"

    # UUID generated by PostgreSQL itself (server_default) so the value is
    # guaranteed unique even if two rows are inserted in the same millisecond.
    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        primary_key=True,
        server_default=text("gen_random_uuid()"),
    )

    username: Mapped[str] = mapped_column(
        String(50),
        nullable=False,
    )

    # Storing the hash, not the password. The application layer (bcrypt) is
    # responsible for hashing before writing and comparing on login.
    password_hash: Mapped[str] = mapped_column(
        String(255),  # bcrypt hashes are 60 chars; 255 gives room for future
        nullable=False,
    )

    role: Mapped[UserRole] = mapped_column(
        PgEnum(UserRole, name="user_role", create_type=True, values_callable=lambda x: [e.value for e in x]),
        nullable=False,
        default=UserRole.STUDENT,
        server_default="student",
    )

    # --- Relationships ---
    # back_populates keeps both sides of the relationship in sync in memory.
    holds: Mapped[list["Hold"]] = relationship(  # type: ignore[name-defined]
        "Hold", back_populates="user", cascade="all, delete-orphan"
    )
    bookings: Mapped[list["Booking"]] = relationship(  # type: ignore[name-defined]
        "Booking", back_populates="user", cascade="all, delete-orphan"
    )

    # --- Constraints ---
    __table_args__ = (
        # Enforce unique usernames at the database level, not just the app level.
        UniqueConstraint("username", name="uq_users_username"),
    )

    def __repr__(self) -> str:
        # Never include password_hash in the repr.
        return f"<User id={self.id} username={self.username!r} role={self.role}>"
